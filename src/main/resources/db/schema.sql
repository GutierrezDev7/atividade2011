CREATE TABLE IF NOT EXISTS usuarios (
    id BIGSERIAL PRIMARY KEY,
    login VARCHAR(120) NOT NULL UNIQUE,
    senha VARCHAR(60) NOT NULL,
    status BOOLEAN NOT NULL DEFAULT TRUE,
    perfil VARCHAR(20) NOT NULL DEFAULT 'CLIENTE'
        CHECK (perfil IN ('ADMIN', 'CLIENTE'))
);

CREATE TABLE IF NOT EXISTS veiculos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca VARCHAR(60) NOT NULL,
    modelo VARCHAR(80) NOT NULL,
    versao VARCHAR(80) NOT NULL,
    ano SMALLINT NOT NULL CHECK (ano BETWEEN 1900 AND 2200),
    preco NUMERIC(12, 2) NOT NULL CHECK (preco >= 0),
    quilometragem INTEGER NOT NULL CHECK (quilometragem >= 0),
    cambio VARCHAR(40) NOT NULL,
    combustivel VARCHAR(40) NOT NULL,
    cor VARCHAR(60) NOT NULL,
    categoria VARCHAR(40) NOT NULL,
    potencia SMALLINT NOT NULL CHECK (potencia >= 0),
    portas SMALLINT NOT NULL CHECK (portas > 0),
    descricao VARCHAR(1000) NOT NULL,
    destaque BOOLEAN NOT NULL DEFAULT FALSE,
    tom VARCHAR(7) NOT NULL
);

CREATE TABLE IF NOT EXISTS propostas (
    id BIGSERIAL PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    email VARCHAR(80) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    veiculo_id INTEGER NOT NULL REFERENCES veiculos (id),
    mensagem VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'NOVA',
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_propostas_criada_em
    ON propostas (criada_em DESC);

